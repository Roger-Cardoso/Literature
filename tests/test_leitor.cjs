const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const storage=new Map();
const area={scrollTop:0,scrollHeight:2000,clientHeight:500,getBoundingClientRect:()=>({top:80})};
const p={offsetHeight:140,textContent:'Um parágrafo estável.',getBoundingClientRect:()=>({top:100,bottom:240})};
const content={querySelectorAll:()=>[p]};
const elements={'scroll-area':area,'content-area':content};
const context={document:{getElementById:id=>elements[id]},Unilit:{ler:(k,d)=>storage.get(k)??d,salvar:(k,v)=>storage.set(k,v)},console};
vm.createContext(context);
const source=fs.readFileSync('js-global/leitor.js','utf8').split("$('abrir-sumario').onclick=")[0];
vm.runInContext(source,context);
vm.runInContext("obra={id_obra:'obra-fixa'};atual={id:'cap-fixo'};pronto=true",context);
vm.runInContext('salvarPosicao()',context);
assert.equal(storage.get('unilit:v2:retomar:obra-fixa').capitulo,'cap-fixo');
area.scrollTop=300;
vm.runInContext('restaurar()',context);
assert.equal(area.scrollTop,0,'Retomada no início não deve pular o cabeçalho');
storage.set('unilit:v2:posicao:obra-fixa:cap-fixo',{fracao:.5,paragrafo:0,trecho:'Texto antigo',deslocamento:0});
vm.runInContext('restaurar()',context);
assert.equal(area.scrollTop,750,'Texto alterado usa percentual como alternativa');
area.scrollTop=300;
storage.set('unilit:v2:posicao:obra-fixa:cap-fixo',{fracao:.2,paragrafo:0,trecho:'Um parágrafo estável.',deslocamento:-20});
vm.runInContext('restaurar()',context);
assert.equal(area.scrollTop,300,'Parágrafo preserva deslocamento negativo após mudança de layout');
assert.equal(vm.runInContext("normalizar('Capítulo SÉRTÃO')",context),'capitulo sertao');
assert.equal(vm.runInContext("limitar('inválido',14,32,19)",context),19);
console.log('Retomada por ID, início do texto, parágrafo estável, fallback e busca sem acentos: OK');
const alvoCena={id:'cena-b',getBoundingClientRect:()=>({top:500}),setAttribute(){},focus(options){this.recebeuFoco=options.preventScroll;}};
content.querySelectorAll=seletor=>seletor==='[id]'?[alvoCena]:[p];
elements['aviso-navegacao']={hidden:true,textContent:''};
area.scrollTop=100;
assert.equal(vm.runInContext("irCena('cena-ausente')",context),false);
assert.equal(vm.runInContext("irCena('cena-b')",context),true);
assert.equal(area.scrollTop,500);
assert.equal(alvoCena.recebeuFoco,true);
assert.equal(elements['aviso-navegacao'].hidden,false);
assert.equal(storage.has('unilit:v2:progresso:obra-fixa'),false,'Pular cena não escreve conclusão');
console.log('Navegação real do leitor: alvo, foco, aviso e ausência de conclusão automática: OK');
